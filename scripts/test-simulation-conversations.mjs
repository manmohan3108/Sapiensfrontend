import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithEsbuild } from 'vite';
import * as React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const path = new URL('../src/app/components/simulation/conversationList.ts', import.meta.url);
const { code } = await transformWithEsbuild(await readFile(path, 'utf8'), 'conversationList.ts', { loader: 'ts' });
const { indexMessages, conversationList } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const event = (sequence, sender, recipient, channel, text = 'Hello') => ({ category: 'messages', actor_id: sender,
  event: { sequence, occurred_at: `2026-11-10T10:${String(sequence).padStart(2, '0')}:00Z`, payload: { sender_id: sender, recipient_id: recipient, channel_id: channel, text } } });
const initial = indexMessages({}, [event(1, 'alice', 'sapien'), event(2, 'sapien', 'bob')], 'sapien');
const channel = { ...event(3, 'alice', 'sapien', 'team'), recipient_ids: ['sapien', 'bob', 'alice'] };
const index = indexMessages(initial, [channel, event(4, 'alice', 'bob')], 'sapien');
assert.equal(index['person:alice'].sequence, 1, 'Channel delivery and other employees’ DMs cannot reorder participant DMs');
assert.equal(index['person:bob'].sequence, 2);
assert.equal(index['channel:team'].sequence, 3);
assert.equal(initial['channel:team'], undefined, 'Previous index stays immutable');
const people = ['alice', 'bob', 'zoe'].map(name => ({ person_id: name, name, direct_sent: 1, direct_received: 1, last_activity_at: '2099-01-01' }));
const channels = [{ channel_id: 'team', title: 'Team', posts: 1 }];
assert.deepEqual(conversationList(people, channels, index).map(row => row.key), ['channel:team', 'person:bob', 'person:alice', 'person:zoe']);
const updated = indexMessages(index, [event(5, 'sapien', 'alice', null, 'Latest reply')], 'sapien');
assert.equal(conversationList(people, channels, updated)[0].key, 'person:alice');
assert.equal(updated['person:alice'].text, 'Latest reply');
assert.equal(indexMessages(updated, [event(1, 'alice', 'sapien')], 'sapien')['person:alice'].sequence, 5, 'Older pages cannot replace latest preview');
assert.deepEqual(indexMessages({}, [event(1, 'alice', 'sapien')], null), {}, 'Missing participant identity must not guess DM ownership');
const invalid = indexMessages({}, [{ ...event(1, 'alice', 'sapien'), event: { ...event(1, 'alice', 'sapien').event, occurred_at: 'invalid' } }], 'sapien');
assert.doesNotThrow(() => conversationList(people, channels, invalid));
globalThis.conversationTest = { React, conversationList };
const componentSource = (await readFile(new URL('../src/app/components/simulation/SimulationConversationList.tsx', import.meta.url), 'utf8')).replace(/^import .*;\r?\n/gm, '');
const renderedModule = await transformWithEsbuild(`const { React, conversationList } = globalThis.conversationTest; const Hash = () => null;\n${componentSource}`, 'SimulationConversationList.tsx', { loader: 'tsx', jsx: 'transform', jsxFactory: 'React.createElement' });
const { SimulationConversationList } = await import('data:text/javascript;base64,' + Buffer.from(renderedModule.code).toString('base64'));
const render = overrides => renderToStaticMarkup(React.createElement(SimulationConversationList, { people, channels, index, filter: 'all', search: '', selected: 'person:bob', loading: false, error: '', onSelect() {}, ...overrides }));
assert.match(render({}), /aria-current="true"/);
assert.match(render({}), /IST/);
assert.doesNotMatch(render({ filter: 'direct' }), />Team</);
assert.doesNotMatch(render({ filter: 'channels' }), />alice</);
assert.match(render({ search: 'absent' }), /No matching conversations/);
assert.match(render({ people: [], channels: [], loading: true }), /Updating conversations/);
assert.match(render({ error: 'Failed' }), /Refresh to retry/);
assert.doesNotThrow(() => render({ index: invalid }));
await transformWithEsbuild(await readFile(new URL('../src/app/pages/SimulationWorldPage.tsx', import.meta.url), 'utf8'), 'SimulationWorldPage.tsx', { loader: 'tsx' });
delete globalThis.conversationTest;
console.log('Simulation conversation ordering checks passed.');
