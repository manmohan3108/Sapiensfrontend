import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithEsbuild } from 'vite';

const harness = { state:undefined, effects:[], requests:[], interval:null };
const browser = new EventTarget();
browser.setInterval = fn => { harness.interval=fn; return 1; };
browser.clearInterval = () => { harness.interval=null; };
const doc = new EventTarget(); doc.visibilityState='visible';
globalThis.badgeTest = { harness, browser, doc };
const source = (await readFile(new URL('../src/app/components/navigation/useConnectionRequestCount.ts',import.meta.url),'utf8')).replace(/^import .*;\r?\n/gm,'');
const prelude = `const {harness:h, browser:window, doc:document}=globalThis.badgeTest;
const useState=()=>[h.state,value=>h.state=value];
const useEffect=fn=>h.effects.push(fn);
const CONNECTION_REQUESTS_UPDATED='updated';
const pendingConnectionCount=data=>data.requests.filter(r=>r.status==='pending').length;
const connectionsService={list:(id,signal)=>new Promise((resolve,reject)=>h.requests.push({id,signal,resolve,reject}))};`;
const {code}=await transformWithEsbuild(prelude+source,'count.ts',{loader:'ts'});
const {useConnectionRequestCount:useCount}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const response=(id,count)=>({sapien_id:id,requests:Array.from({length:count},()=>({status:'pending'}))});
const flush=async()=>{await Promise.resolve();await Promise.resolve();};
useCount('58','account-a'); let cleanup=harness.effects.pop()();
harness.requests[0].resolve(response(58,3)); await flush();
assert.equal(useCount('58','account-a'),3);
assert.equal(useCount('59','account-a'),null,'Do not show previous Sapien count');
assert.equal(useCount('58','account-b'),null,'Do not show previous account count');
harness.interval(); const old=harness.requests.at(-1);
const update=new Event('updated'); update.detail=response(58,0); browser.dispatchEvent(update);
assert(old.signal.aborted,'A post-action refresh supersedes a poll');
old.resolve(response(58,9)); await flush();
assert.equal(harness.state.count,0,'Late poll cannot restore handled requests');
const other=new Event('updated'); other.detail=response(59,5); browser.dispatchEvent(other);
assert.equal(harness.state.count,0,'Ignore other Sapien updates');
doc.visibilityState='hidden'; const before=harness.requests.length; harness.interval();
assert.equal(harness.requests.length,before,'No hidden-tab polling');
doc.visibilityState='visible'; doc.dispatchEvent(new Event('visibilitychange'));
const last=harness.requests.at(-1); cleanup();
assert(last.signal.aborted); last.resolve(response(58,7)); await flush();
assert.equal(harness.state.count,0,'Unmounted requests cannot update the badge');
assert.equal(harness.interval,null);
delete globalThis.badgeTest;
console.log('Connection badge lifecycle passed: scope isolation, action refresh, stale responses, hidden-tab polling and cleanup.');
