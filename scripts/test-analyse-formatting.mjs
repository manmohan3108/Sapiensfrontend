import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import * as React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { transformWithEsbuild } from 'vite';
import { FormattedText } from './load-formatted-text.mjs';

globalThis.analyseFormatting = { React, FormattedText, expanded:false };
const source = (await readFile(new URL('../src/app/components/analyse/DiagnosticPrimitives.tsx', import.meta.url), 'utf8')).replace(/^import .*;\r?\n/gm, '');
const prelude = `const {React,FormattedText}=globalThis.analyseFormatting;
const useId=()=>"detail-text";
const useState=()=>[globalThis.analyseFormatting.expanded,value=>globalThis.analyseFormatting.expanded=value];`;
const { code } = await transformWithEsbuild(prelude + source, 'DiagnosticPrimitives.tsx', {loader:'tsx',jsx:'transform',jsxFactory:'React.createElement'});
const { DiagnosticText } = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const text = '**Assessment**\n\n- First\n- Second\n\n| Result | Evidence |\n| --- | --- |\n| Saved | `record_1` |';
let rendered=renderToStaticMarkup(React.createElement(DiagnosticText,{text}));
assert.match(rendered, /<strong>Assessment<\/strong>/);
assert.match(rendered, /<ul>[\s\S]*<li>Second<\/li>/);
assert.match(rendered, /<table>[\s\S]*<code>record_1<\/code>/);
const tree=DiagnosticText({text,limit:20});
assert.match(renderToStaticMarkup(tree), /Show full text/);
tree.props.children[1].props.onClick();
rendered=renderToStaticMarkup(React.createElement(DiagnosticText,{text,limit:20}));
assert.match(rendered, /<table>/);
assert.match(rendered, /Show less/);
rendered=renderToStaticMarkup(React.createElement(DiagnosticText,{text:'**literal_id**',plain:true}));
assert(rendered.includes('**literal_id**'));
assert(!rendered.includes('<strong>'));
delete globalThis.analyseFormatting;
console.log('Analyse formatting passed: bold, lists, tables and full-text expansion using the production renderer.');
