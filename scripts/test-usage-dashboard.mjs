import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transformWithEsbuild } from 'vite';
import * as React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
globalThis.usageTest = { React };
const source = (await readFile(new URL('../src/app/components/analyse/UsageDashboard.tsx', import.meta.url), 'utf8')).replace(/^import .*;\r?\n/gm, '');
const { code } = await transformWithEsbuild(`const React = globalThis.usageTest.React; const {useState} = React; const RefreshCw = () => null;\n${source}`, 'UsageDashboard.tsx', { loader: 'tsx', jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment' });
const { UsageDashboard } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const data = { kind: 'llm', scope: 'sapien:12', today: '2026-11-13', today_total: 32, today_by_tier: { fast: 30, unknown: 2 }, today_by_purpose: { conversation: 10, planning: 22 }, sapien_limits: { fast: 100, unused: 20 }, allowance_limits: { conversation: 50 }, today_by_allowance: { conversation: 10 }, history: [{ date: '2026-11-12', total: 12 }] };
const empty = { global: null, sapien: null, errors: [], loading: false };
const render = (state = {}) => renderToStaticMarkup(React.createElement(UsageDashboard, { states: { llm: { ...empty, sapien: data, ...state }, embedding: empty }, sapienId: '12', sapienName: 'Test Sapien', onRefresh() {} }));
const html = render();
assert.ok(!html.includes('<details'), 'Personal tier and purpose breakdowns must stay visible');
assert.match(html, /Today by purpose/);
assert.match(html, /30<\/strong><span> \/ 100/);
assert.match(html, /0<\/strong><span> \/ 20/);
assert.match(html, /Not provided/);
assert.match(html, /10<\/strong><span> \/ 50/, 'Conversation allowance uses allowance usage, not tier usage');
assert.match(html, /not remaining balance/);
assert.match(html, /2026-11-12/);
assert.match(render({ sapien: null, loading: true }), /Loading recorded usage/);
assert.match(render({ sapien: null, errors: [{ scope: 'Test Sapien', message: 'Offline' }] }), /role="alert"/);
assert.match(render({ sapien: { ...data, today_by_tier: {}, sapien_limits: {}, today_by_purpose: {}, history: [] } }), /No calls attributed/);
await transformWithEsbuild(await readFile(new URL('../src/app/components/workspace/LlmUsageDialog.tsx', import.meta.url), 'utf8'), 'LlmUsageDialog.tsx', { loader: 'tsx' });
delete globalThis.usageTest;
console.log('Usage dashboard render and data interpretation checks passed.');
